<?php
/** Slice 8 proof — JSON mode and agents (agents-feeds.md "Proof": json.php). */
require __DIR__ . '/lib.php';

$s = proposal_world();
$m = $s['manuals'];
$p = $s['policies'];
$shape = static fn (array $b): bool => ($b['ok'] ?? false) === true && isset($b['did'], $b['record_id'], $b['location'], $b['refresh']);
$cara = ['X-Action-Token: ' . person_token(CARA)];
$admin = ['X-Action-Token: ' . person_token(OWNER)];
$priya = ['X-Action-Token: ' . person_token(PRIYA)];
$arch = as_agent(run_token(ARCHIVIST, 7901));
$expert = as_agent(run_token(EXPERT, 7902));
pdo()->exec("UPDATE archivist_proposals SET status = 'dismissed', decided_at = now() WHERE base_id = $m AND status = 'proposed'");
chat_state(['chat' => ['run_id' => 7001, 'status' => 'succeeded', 'finished' => true, 'reply' => 'Done.']]);

echo "1. The Archivist\n";
[$c, $b] = act_token('/proposals/save.php', ['base' => $m, 'kind' => 'unverified', 'title' => 'SMOKE json', 'reason' => 'Because.', 'subject_type' => 'question', 'subject_id' => $s['q_unver'], 'payload' => '{}'], $arch);
$pid = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $shape($b) && $b['location'] === '/bases/' . $m . '/proposals#proposal-' . $pid && $b['refresh'] === 'proposalChanged' && $b['base_id'] === $m, 'archivist_propose under a run token: {ok, did, record_id, location, refresh}');
[$c, $b] = act_token('/notifications/send.php', ['base' => $p, 'title' => 'SMOKE json note', 'body' => 'A note.'], $arch);
ok($c === 200 && $shape($b) && $b['record_id'] === $p && $b['location'] === '/bases/' . $p && isset($b['recipients']), 'notification answers the shape with the recipients');
[$c, $b] = act_token('/proposals/save.php', ['base' => $m, 'kind' => 'unverified', 'title' => 't'], $arch);
ok($c === 422 && ($b['error']['code'] ?? '') === 'invalid', 'a refusal: 422 {error: {code: invalid}} ("' . json_msg($b) . '")');
[$c, $b] = act_token('/proposals/accept.php', ['proposal' => $pid], $arch);
ok($c === 403 && proposal_row($pid)['status'] === 'proposed', 'the Archivist\'s token is refused archivist_proposal_accept → 403 ("' . json_msg($b) . '")');
[$c, $b] = act_token('/proposals/dismiss.php', ['proposal' => $pid], $arch);
ok($c === 403, '…and archivist_proposal_dismiss');
[$c] = act_token('/admin/dispatches/retry.php', ['dispatch' => 1], $arch);
ok($c === 403, '…and dispatch_retry (agents.settings)');
[$c] = act_token('/agents/propose-areas.php', ['base' => $p], $arch);
[$c2] = act_token('/agents/draft-guidelines.php', ['base' => $p], $arch);
ok($c === 403 && $c2 === 403, '…and the two requests for the expert (people only)');

echo "2. A person's token\n";
[$c, $b] = act_token('/proposals/accept.php', ['proposal' => $pid], $cara);
ok($c === 200 && $shape($b) && $b['record_id'] === $pid && $b['effect'] === 'open_question' && $b['location'] === '/questions/' . $s['q_unver'], 'archivist_proposal_accept: the shape, the effect, the screen it lands on');
[$c, $b] = act_token('/proposals/save.php', ['base' => $m, 'kind' => 'limit_near', 'title' => 'SMOKE json 2', 'reason' => 'r', 'subject_type' => 'base', 'subject_id' => $m, 'payload' => '{"pct": 95}'], $arch);
$pid2 = (int) $b['record_id'];
[$c, $b] = act_token('/proposals/dismiss.php', ['proposal' => $pid2, 'note' => 'Not now.'], $cara);
ok($c === 200 && $shape($b) && $b['record_id'] === $pid2 && proposal_payload($pid2)['decision_note'] === 'Not now.', 'archivist_proposal_dismiss: the shape');
[$c, $b] = act_token('/proposals/accept.php', ['proposal' => $pid2], $cara);
ok($c === 422 && ($b['error']['code'] ?? '') === 'invalid' && isset($b['error']['fields']['proposal']), 'a decided proposal → 422 {error: {code: invalid, fields: {proposal}}}');
[$c, $b] = act_token('/proposals/accept.php', ['proposal' => $pid2], $priya);
ok($c === 403, 'Priya\'s token → 403');
[$c, $b] = act_token('/agents/propose-areas.php', ['base' => $p], $cara);
ok($c === 200 && $shape($b) && $b['kind'] === 'propose_areas' && $b['existing'] === false && $b['refresh'] === 'areasChanged', 'areas_propose_request: the shape (kind, existing)');
[$c, $b] = act_token('/agents/draft-guidelines.php', ['base' => $p], $cara);
ok($c === 200 && $shape($b) && $b['kind'] === 'draft_guidelines' && $b['refresh'] === 'guidelinesChanged', 'guidelines_draft_request: the shape');
[$c, $b] = act_token('/agents/propose-areas.php', ['base' => $p], $cara);
ok($c === 200 && $b['existing'] === true, '…a second one answers existing true');
[$c, $b] = act_token('/agents/propose-areas.php', ['base' => $p], $priya);
ok($c === 403, 'Priya\'s token → 403');
worker_at();
$did = (int) one("SELECT id FROM agent_dispatches WHERE kind = 'propose_areas' AND base_id = :b ORDER BY id DESC LIMIT 1", ['b' => $p]);
pdo()->exec("UPDATE agent_dispatches SET status = 'failed', detail = 'x', answered_at = now() WHERE id = $did");
[$c, $b] = act_token('/admin/dispatches/retry.php', ['dispatch' => $did], $admin);
ok($c === 200 && $shape($b) && $b['record_id'] === $did && $b['location'] === '/admin/dispatches#dispatch-row-' . $did, 'dispatch_retry under the admin\'s token: the shape');
[$c] = act_token('/admin/dispatches/retry.php', ['dispatch' => $did], $cara);
ok($c === 403, 'a curator\'s token may not retry (agents.settings)');

echo "3. Feeds\n";
pdo()->exec("DELETE FROM feeds WHERE base_id = $m AND arguments->>'space' IS DISTINCT FROM 'smoke-stopped'");
[$c, $b] = act_token('/feeds/save.php', ['base' => $m, 'provider' => 'spaces', 'tool' => 'pages_index', 'arguments' => '{"space": "json"}', 'every_minutes' => 90], $expert);
$fid = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $shape($b) && $b['location'] === '/bases/' . $m . '/feeds#feed-' . $fid && $b['refresh'] === 'feedChanged' && json_decode((string) feed_row($fid)['arguments'], true) === ['space' => 'json'], 'feed_save under the expert\'s token (arguments as JSON): the shape');
[$c, $b] = act_token('/feeds/save.php', ['feed' => $fid, 'every_minutes' => 30, '_partial' => '1'], $expert);
ok($c === 200 && (int) feed_row($fid)['every_minutes'] === 30 && json_decode((string) feed_row($fid)['arguments'], true) === ['space' => 'json'], '_partial=1 on feed_save keeps the arguments');
[$c, $b] = act_token('/feeds/save.php', ['feed' => $fid, 'every_minutes' => 3, '_partial' => '1'], $expert);
ok($c === 422 && ($b['error']['code'] ?? '') === 'invalid' && isset($b['error']['fields']['every_minutes']), '422 {error: {code: invalid, fields}}');
[$c, $b] = act_token('/feeds/sync.php', ['feed' => $fid], $expert);
ok($c === 200 && $shape($b) && $b['record_id'] === $fid, 'feed_sync: the shape');
[$c, $b] = act_token('/feeds/delete.php', ['feed' => $fid], $cara);
ok($c === 200 && $shape($b) && $b['record_id'] === $fid && $b['forgotten'] === 0 && feed_row($fid) === [], 'feed_delete under a person\'s token: the shape');

echo "4. The screens as JSON, and the registry\n";
[$c, $d] = screen(as_member(CARA), '/bases/' . $m . '/proposals');
ok($c === 200 && isset($d['proposals'], $d['counts'], $d['status']), 'proposals: ' . implode(', ', array_keys($d)));
[$c, $d] = screen(as_member(OWNER), '/admin/proposals');
ok($c === 200 && isset($d['proposals']), 'admin-proposals');
[$c, $d] = screen(as_member(OWNER), '/admin/dispatches');
ok($c === 200 && isset($d['dispatches'], $d['total']) && count($d['dispatches']) > 0 && isset($d['dispatches'][0]['reply_excerpt']) && !isset($d['dispatches'][0]['utterance']), 'dispatches: the facts, never the utterance');
[$c, $d] = screen(as_member(CARA), '/admin/dispatches');
ok($c === 403, 'a curator may not open the dispatches');
[$c, $d] = screen(as_member(CARA), '/bases/' . $m . '/feeds');
ok($c === 200 && isset($d['feeds'], $d['tools']), 'feeds');
[$c, $d] = screen(as_member(CARA), '/feeds/new?base=' . $m);
ok($c === 200 && $d['feed'] === null && count($d['tools']) === 2 && isset($d['areas']), 'feed-add');
$reg = json_decode(file_get_contents(APP_ROOT . '/mcp/action_registry.json'), true);
$acts = ['archivist_propose', 'archivist_proposal_accept', 'archivist_proposal_dismiss', 'notification', 'feed_save', 'feed_sync', 'feed_delete', 'dispatch_retry', 'areas_propose_request', 'guidelines_draft_request'];
$screens = ['proposals', 'admin-proposals', 'feeds', 'feed-add', 'feed-edit', 'dispatches'];
$ba = count(array_filter($acts, static fn ($x) => !empty($reg['actions'][$x]['built'])));
$bs = count(array_filter($screens, static fn ($x) => !empty($reg['screens'][$x]['built'])));
ok($ba === 10 && $bs === 6, "the registry reads 6 screens and 10 actions of this slice built ($bs, $ba)");
$people = array_filter($acts, static fn ($x) => ($reg['actions'][$x]['agent'] ?? true) === false);
sort($people);
ok($people === ['archivist_proposal_accept', 'archivist_proposal_dismiss', 'areas_propose_request', 'guidelines_draft_request'], 'people only: accept, dismiss and the two requests: ' . implode(', ', $people));
$paused = array_values(array_filter($acts, static fn ($x) => !empty($reg['actions'][$x]['approval'])));
ok($paused === ['feed_delete'], 'the only one that pauses for an agent: feed_delete');
finish();
